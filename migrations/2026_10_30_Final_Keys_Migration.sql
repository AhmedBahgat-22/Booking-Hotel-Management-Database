/*
  Booking.com Hotel Database Management System
  Final key migration for the EXISTING BookingSystemDB_Dev database.

  PURPOSE
  - Promote Booking.Booking_ID to the primary key.
  - Promote Payment.Payment_ID to the primary key.
  - Preserve legacy Booking triple uniqueness (Customer_ID, Room_ID, CheckInDate).
  - Replace the Payment -> Booking composite FK with the Booking_ID FK.
  - Make Payment.Booking_ID mandatory.
  - Preserve existing rows and their correct mappings.

  IMPORTANT
  - ONLY run against BookingSystemDB_Dev, NEVER the original BookingSystemDB.
  - Requires the preparation steps completed previously (Booking_ID, Payment_ID,
    Booking_Audit.Booking_ID, mapping, and initial constraints).
  - Runs inside a transaction, rolls back DDL if an error occurs.
  - Does not drop data tables or delete rows.
  - Original composite columns in Payment remain for legacy compatibility;
    they will NOT auto-update if Customer_ID / Room_ID / CheckInDate changes in Booking.
    Future applications should use Payment.Booking_ID as the reference.
  - The final Payment FK uses NO ACTION on DELETE, protecting payment history.
*/
USE [BookingSystemDB_Dev];
GO
SET NOCOUNT ON;
SET XACT_ABORT ON;

BEGIN TRY
    IF DB_NAME() <> N'BookingSystemDB_Dev'
        THROW 51001, 'STOP: Select BookingSystemDB_Dev, not the original database.', 1;

    IF OBJECT_ID(N'dbo.Booking', N'U') IS NULL
       OR OBJECT_ID(N'dbo.Payment', N'U') IS NULL
       OR OBJECT_ID(N'dbo.Booking_Audit', N'U') IS NULL
        THROW 51002, 'STOP: Required tables are missing.', 1;

    IF COL_LENGTH(N'dbo.Booking', N'Booking_ID') IS NULL
       OR COL_LENGTH(N'dbo.Payment', N'Booking_ID') IS NULL
       OR COL_LENGTH(N'dbo.Payment', N'Payment_ID') IS NULL
       OR COL_LENGTH(N'dbo.Booking_Audit', N'Booking_ID') IS NULL
        THROW 51003, 'STOP: Run the previous column and mapping steps first.', 1;

    -- Intentional one-time migration. Never silently rerun after PK conversion.
    IF NOT EXISTS (
        SELECT 1 FROM sys.key_constraints
        WHERE parent_object_id = OBJECT_ID(N'dbo.Booking')
          AND name = N'PK_Booking' AND type = N'PK'
    )
       OR NOT EXISTS (
        SELECT 1 FROM sys.key_constraints
        WHERE parent_object_id = OBJECT_ID(N'dbo.Payment')
          AND name = N'PK_Payment' AND type = N'PK'
    )
        THROW 51004, 'STOP: Unexpected primary key names or schema.', 1;

    IF EXISTS (
        SELECT 1
        FROM sys.index_columns ic
        JOIN sys.key_constraints kc
          ON kc.parent_object_id = ic.object_id
         AND kc.unique_index_id = ic.index_id
        JOIN sys.columns c
          ON c.object_id = ic.object_id AND c.column_id = ic.column_id
        WHERE kc.name IN (N'PK_Booking', N'PK_Payment')
          AND kc.type = N'PK' AND c.name IN (N'Booking_ID', N'Payment_ID')
          AND ic.key_ordinal > 0
    )
        THROW 51005, 'STOP: A new ID is already part of a primary key. Do not rerun.', 1;

    -- Detect FKs from other tables that would make dropping the old PK unsafe.
    IF EXISTS (
        SELECT 1
        FROM sys.foreign_keys
        WHERE referenced_object_id = OBJECT_ID(N'dbo.Booking')
          AND name NOT IN (N'FK_Payment_Booking', N'FK_Payment_BookingID')
    )
        THROW 51006, 'STOP: Unexpected foreign key references Booking. Review manually.', 1;

    IF NOT EXISTS (
        SELECT 1 FROM sys.foreign_keys
        WHERE parent_object_id = OBJECT_ID(N'dbo.Payment')
          AND name = N'FK_Payment_Booking'
    )
      OR NOT EXISTS (
        SELECT 1 FROM sys.foreign_keys
        WHERE parent_object_id = OBJECT_ID(N'dbo.Payment')
          AND name = N'FK_Payment_BookingID'
    )
      OR NOT EXISTS (
        SELECT 1 FROM sys.key_constraints
        WHERE parent_object_id = OBJECT_ID(N'dbo.Booking')
          AND name = N'UQ_Booking_BookingID' AND type = N'UQ'
    )
        THROW 51007, 'STOP: Expected old/new FK or UNIQUE constraint is missing.', 1;

    -- Verify each new ID is present, unique, and generated by IDENTITY.
    IF EXISTS (SELECT 1 FROM dbo.Booking WHERE Booking_ID IS NULL)
       OR EXISTS (SELECT Booking_ID FROM dbo.Booking GROUP BY Booking_ID HAVING COUNT_BIG(*) > 1)
       OR EXISTS (SELECT 1 FROM dbo.Payment WHERE Booking_ID IS NULL OR Payment_ID IS NULL)
       OR EXISTS (SELECT Payment_ID FROM dbo.Payment GROUP BY Payment_ID HAVING COUNT_BIG(*) > 1)
        THROW 51008, 'STOP: Missing or duplicate Booking_ID/Payment_ID.', 1;

    IF NOT EXISTS (
        SELECT 1 FROM sys.columns
        WHERE object_id = OBJECT_ID(N'dbo.Booking')
          AND name = N'Booking_ID' AND is_identity = 1
    ) OR NOT EXISTS (
        SELECT 1 FROM sys.columns
        WHERE object_id = OBJECT_ID(N'dbo.Payment')
          AND name = N'Payment_ID' AND is_identity = 1
    )
        THROW 51009, 'STOP: Expected IDENTITY columns are missing.', 1;

    IF EXISTS (
        SELECT 1
        FROM dbo.Payment p
        LEFT JOIN dbo.Booking b ON p.Booking_ID = b.Booking_ID
        WHERE b.Booking_ID IS NULL
           OR p.Customer_ID <> b.Customer_ID
           OR p.Room_ID <> b.Room_ID
           OR p.CheckInDate <> b.CheckInDate
    )
        THROW 51010, 'STOP: One or more payment-to-booking mappings are invalid.', 1;

    DECLARE @bookingCount BIGINT = (SELECT COUNT_BIG(*) FROM dbo.Booking);
    DECLARE @paymentCount BIGINT = (SELECT COUNT_BIG(*) FROM dbo.Payment);

    BEGIN TRANSACTION;

    -- Preserve the uniqueness rule once enforced by the old Booking PK.
    ALTER TABLE dbo.Booking
      ADD CONSTRAINT UQ_Booking_LegacyComposite
          UNIQUE NONCLUSTERED (Customer_ID, Room_ID, CheckInDate);

    -- A FK cannot outlive the key/index it references, so drop both FKs first.
    ALTER TABLE dbo.Payment DROP CONSTRAINT FK_Payment_Booking;
    ALTER TABLE dbo.Payment DROP CONSTRAINT FK_Payment_BookingID;

    -- Replace legacy composite primary keys with stable IDENTITY primary keys.
    ALTER TABLE dbo.Payment DROP CONSTRAINT PK_Payment;
    ALTER TABLE dbo.Booking DROP CONSTRAINT PK_Booking;
    ALTER TABLE dbo.Booking DROP CONSTRAINT UQ_Booking_BookingID;

    ALTER TABLE dbo.Booking
      ADD CONSTRAINT PK_Booking PRIMARY KEY CLUSTERED (Booking_ID);

    ALTER TABLE dbo.Payment
      ADD CONSTRAINT PK_Payment PRIMARY KEY CLUSTERED (Payment_ID);

    ALTER TABLE dbo.Payment ALTER COLUMN Booking_ID INT NOT NULL;

    ALTER TABLE dbo.Payment WITH CHECK
      ADD CONSTRAINT FK_Payment_BookingID
          FOREIGN KEY (Booking_ID) REFERENCES dbo.Booking(Booking_ID);

    ALTER TABLE dbo.Payment CHECK CONSTRAINT FK_Payment_BookingID;

    IF @bookingCount <> (SELECT COUNT_BIG(*) FROM dbo.Booking)
       OR @paymentCount <> (SELECT COUNT_BIG(*) FROM dbo.Payment)
        THROW 51011, 'STOP: Row counts changed unexpectedly.', 1;

    IF EXISTS (
        SELECT 1
        FROM dbo.Payment p
        LEFT JOIN dbo.Booking b ON p.Booking_ID = b.Booking_ID
        WHERE b.Booking_ID IS NULL
           OR p.Customer_ID <> b.Customer_ID
           OR p.Room_ID <> b.Room_ID
           OR p.CheckInDate <> b.CheckInDate
    )
        THROW 51012, 'STOP: A payment mapping no longer matches its booking.', 1;

    COMMIT TRANSACTION;
    PRINT 'SUCCESS: New Booking and Payment primary keys installed. All mappings intact.';

    -- Final verification: three result tables will appear in Results.
    SELECT N'Booking' AS TableName, COUNT_BIG(*) AS TotalRows FROM dbo.Booking
    UNION ALL
    SELECT N'Payment', COUNT_BIG(*) FROM dbo.Payment;

    SELECT kc.name AS PrimaryKeyName,
           OBJECT_NAME(kc.parent_object_id) AS TableName,
           c.name AS PrimaryKeyColumn
    FROM sys.key_constraints kc
    JOIN sys.index_columns ic
      ON ic.object_id = kc.parent_object_id
     AND ic.index_id = kc.unique_index_id
     AND ic.key_ordinal > 0
    JOIN sys.columns c
      ON c.object_id = ic.object_id AND c.column_id = ic.column_id
    WHERE kc.type = N'PK'
      AND kc.parent_object_id IN (OBJECT_ID(N'dbo.Booking'), OBJECT_ID(N'dbo.Payment'))
    ORDER BY TableName, ic.key_ordinal;

    SELECT fk.name AS ForeignKeyName,
           OBJECT_NAME(fk.parent_object_id) AS SourceTable,
           OBJECT_NAME(fk.referenced_object_id) AS TargetTable,
           fk.is_disabled AS IsDisabled,
           fk.is_not_trusted AS IsNotTrusted,
           fk.delete_referential_action_desc AS OnDelete
    FROM sys.foreign_keys fk
    WHERE fk.parent_object_id = OBJECT_ID(N'dbo.Payment')
      AND fk.referenced_object_id = OBJECT_ID(N'dbo.Booking');
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
    SELECT ERROR_NUMBER() AS ErrorNumber,
           ERROR_MESSAGE() AS ErrorMessage,
           N'NO COMMIT: investigate before running anything else' AS Note;
    THROW;
END CATCH;
GO
